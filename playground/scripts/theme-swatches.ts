// Writes src/themeSwatches.ts: a few chrome colors per theme family, for the theme picker's swatches.
// Themes load lazily in the page, so the picker can't read them all; rerun after changing FAMILIES:
//   bun scripts/theme-swatches.ts
import { themes } from "@pierre/theming/themes";
import { FAMILIES, chromeVars, withRealColors } from "../src/themeColors";

const catalog = [themes].flat();
const find = (name: string) => {
  for (const source of catalog) {
    const theme = "getTheme" in source ? source.getTheme(name) : source.getThemes().find((t) => t.name === name);
    if (theme) return theme;
  }
  throw new Error(`no theme ${name}`);
};

/** [background, panel, accent] for one theme. */
async function swatch(name: string) {
  const vars = chromeVars(withRealColors(await find(name).load()));
  return [vars["--bg"], vars["--panel"] ?? vars["--bg"], vars["--accent"] ?? vars["--fg"]] as string[];
}

const out: Record<string, { light: string[]; dark: string[] }> = {};
for (const [, light, dark] of Object.values(FAMILIES).flat()) out[light] = { light: await swatch(light), dark: await swatch(dark) };

const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: { light: ${JSON.stringify(v.light)}, dark: ${JSON.stringify(v.dark)} },`)
  .join("\n");
await Bun.write(
  new URL("../src/themeSwatches.ts", import.meta.url),
  `// Generated by scripts/theme-swatches.ts; don't edit.\n/** Per family (by light variant): [background, panel, accent] for each scheme. */\nexport const SWATCHES: Record<string, { light: string[]; dark: string[] }> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(out).length} families`);
