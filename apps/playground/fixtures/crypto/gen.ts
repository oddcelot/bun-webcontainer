// Writes data.ts: the keys and the node-made (random: ECDSA, PSS, OAEP) outputs that cases.ts checks both Bun and the
// playground against. Run with node (native Bun has no chacha20-poly1305):  node fixtures/crypto/gen.ts
import crypto from "node:crypto";
import { writeFileSync } from "node:fs";

const pem = (k: crypto.KeyObject, type = "pkcs8") => k.export({ type, format: "pem" } as never) as string;
const msg = Buffer.from("the message that is signed");
const keys = {
  rsa: crypto.generateKeyPairSync("rsa", { modulusLength: 2048 }),
  ec256: crypto.generateKeyPairSync("ec", { namedCurve: "P-256" }),
  ec384: crypto.generateKeyPairSync("ec", { namedCurve: "P-384" }),
  ed: crypto.generateKeyPairSync("ed25519"),
};
const hex = (b: Buffer) => b.toString("hex");
const PSS = crypto.constants.RSA_PKCS1_PSS_PADDING;
const data = {
  rsaPrivate: pem(keys.rsa.privateKey),
  ec256Private: pem(keys.ec256.privateKey),
  ec384Private: pem(keys.ec384.privateKey),
  edPrivate: pem(keys.ed.privateKey),
  ec256Der: hex(crypto.sign("sha256", msg, keys.ec256.privateKey)),
  ec256P1363: hex(crypto.sign("sha256", msg, { key: keys.ec256.privateKey, dsaEncoding: "ieee-p1363" })),
  ec384Der: hex(crypto.sign("sha384", msg, keys.ec384.privateKey)),
  ec384P1363: hex(crypto.sign("sha512", msg, { key: keys.ec384.privateKey, dsaEncoding: "ieee-p1363" })),
  pssMax: hex(crypto.sign("sha256", msg, { key: keys.rsa.privateKey, padding: PSS })),
  pss20: hex(crypto.sign("sha256", msg, { key: keys.rsa.privateKey, padding: PSS, saltLength: 20 })),
  pss384: hex(crypto.sign("sha384", msg, { key: keys.rsa.privateKey, padding: PSS, saltLength: crypto.constants.RSA_PSS_SALTLEN_DIGEST })),
  oaepSha1: hex(crypto.publicEncrypt(keys.rsa.publicKey, Buffer.from("oaep default"))),
  oaepSha256: hex(crypto.publicEncrypt({ key: keys.rsa.publicKey, oaepHash: "sha256", oaepLabel: Buffer.from("label") }, Buffer.from("oaep sha256 label"))),
  pkcs1: hex(crypto.publicEncrypt({ key: keys.rsa.publicKey, padding: crypto.constants.RSA_PKCS1_PADDING }, Buffer.from("pkcs1 v1.5"))),
};
const body = Object.entries(data)
  .map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};\n`)
  .join("");
writeFileSync(new URL("./data.ts", import.meta.url), `// Generated by gen.ts (node): keys and node-made outputs. Don't edit.\nexport const message = ${JSON.stringify(msg.toString())};\n${body}`);
